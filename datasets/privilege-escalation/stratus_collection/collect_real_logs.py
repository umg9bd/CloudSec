"""
Pulls CloudTrail logs generated by run_detonations.py down from S3,
decompresses them into the same plain-JSON "Records" structure used by
aws_dataset/CloudTrail (so explore.ipynb's extraction cell can point at
this folder too), and cross-references each manifest.csv run against the
actual delivered events to confirm the *right* events arrived -- not just
that some file exists (see the smoke-test writeup for why that matters).

Usage:
    python collect_real_logs.py
    python collect_real_logs.py --bucket stratus-redteam-cloudtrail-536697249497
"""

import argparse
import csv
import gzip
import json
import subprocess
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

from stratus_techniques import TECHNIQUES

SCRIPT_DIR = Path(__file__).parent
RAW_DIR = SCRIPT_DIR / "raw_s3"
ORGANIZED_DIR = SCRIPT_DIR.parent / "stratus_own_runs" / "CloudTrail"

MATCH_BUFFER = timedelta(minutes=10)  # tolerance around [start_ts, end_ts] for event matching

EXPECTED_BY_TECHNIQUE = {t["id"]: t["expected_events"] for t in TECHNIQUES}


def sync_from_s3(bucket, account):
    RAW_DIR.mkdir(parents=True, exist_ok=True)
    prefix = f"s3://{bucket}/AWSLogs/{account}/CloudTrail/"
    print(f"Syncing {prefix} -> {RAW_DIR}")
    result = subprocess.run(
        ["aws", "s3", "sync", prefix, str(RAW_DIR)],
        capture_output=True, text=True,
    )
    if result.returncode != 0:
        print("ERROR running aws s3 sync:", result.stderr, file=sys.stderr)
        sys.exit(1)
    print(result.stdout.strip() or "(no new files)")


def decompress_and_organize():
    """Decompress every .json.gz under RAW_DIR into plain .json files under
    ORGANIZED_DIR, and return a flat list of all parsed CloudTrail records
    with their eventTime as datetime objects."""
    ORGANIZED_DIR.mkdir(parents=True, exist_ok=True)
    all_records = []
    gz_files = sorted(RAW_DIR.rglob("*.json.gz"))
    print(f"Found {len(gz_files)} compressed log files")

    for gz_path in gz_files:
        out_path = ORGANIZED_DIR / (gz_path.stem)  # strips .gz, keeps .json
        if not out_path.exists():
            with gzip.open(gz_path, "rt") as fh:
                data = json.load(fh)
            with open(out_path, "w") as out_fh:
                json.dump(data, out_fh)
        else:
            with open(out_path) as fh:
                data = json.load(fh)

        for ev in data.get("Records", []):
            ts = ev.get("eventTime")
            if ts:
                try:
                    ev["_parsed_time"] = datetime.strptime(ts, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)
                except ValueError:
                    continue
                all_records.append(ev)

    print(f"Decompressed into {ORGANIZED_DIR} ({len(all_records)} total events parsed)")
    return all_records


def parse_manifest_ts(s):
    return datetime.fromisoformat(s)


def verify_manifest(all_records, manifest_path, verified_path):
    if not manifest_path.exists():
        print(f"No {manifest_path.name} found yet -- run run_detonations.py --collector <you> first.")
        return

    with open(manifest_path) as f:
        rows = list(csv.DictReader(f))

    out_fields = list(rows[0].keys()) + ["logs_confirmed", "matched_event_count"]
    verified_rows = []

    for row in rows:
        if not row["end_ts_utc"]:
            row["logs_confirmed"] = "run_incomplete"
            row["matched_event_count"] = 0
            verified_rows.append(row)
            continue

        start = parse_manifest_ts(row["start_ts_utc"]) - MATCH_BUFFER
        end = parse_manifest_ts(row["end_ts_utc"]) + MATCH_BUFFER
        expected = EXPECTED_BY_TECHNIQUE.get(row["technique_id"], [])

        matches = [
            ev for ev in all_records
            if start <= ev["_parsed_time"] <= end and ev.get("eventName") in expected
        ]
        row["matched_event_count"] = len(matches)
        row["logs_confirmed"] = "yes" if matches else "NOT YET DELIVERED"
        verified_rows.append(row)

    with open(verified_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=out_fields)
        writer.writeheader()
        writer.writerows(verified_rows)

    confirmed = sum(1 for r in verified_rows if r["logs_confirmed"] == "yes")
    pending = sum(1 for r in verified_rows if r["logs_confirmed"] == "NOT YET DELIVERED")
    incomplete = sum(1 for r in verified_rows if r["logs_confirmed"] == "run_incomplete")
    print(f"\n{verified_path.name}: {confirmed} confirmed, {pending} not yet delivered, {incomplete} incomplete runs")
    if pending:
        print("Re-run this script again in ~15-20 minutes to pick up delayed deliveries.")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--collector", type=str, required=True,
                         help="Same name/handle you used with run_detonations.py --collector")
    parser.add_argument("--bucket", required=True,
                         help="Your own CloudTrail S3 bucket name (each teammate has their own)")
    parser.add_argument("--account", required=True, help="Your own AWS account ID")
    args = parser.parse_args()

    manifest_path = SCRIPT_DIR / f"manifest_{args.collector}.csv"
    verified_path = SCRIPT_DIR / f"manifest_{args.collector}_verified.csv"

    sync_from_s3(args.bucket, args.account)
    all_records = decompress_and_organize()
    verify_manifest(all_records, manifest_path, verified_path)


if __name__ == "__main__":
    main()
